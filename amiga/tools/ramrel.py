#!/usr/bin/env python3
"""List the places that hold Genesis RAM window addresses (build step of the Amiga port)."""
import struct, sys

HUNK_UNIT, HUNK_NAME, HUNK_CODE, HUNK_DATA, HUNK_BSS = 0x3E7, 0x3E8, 0x3E9, 0x3EA, 0x3EB
HUNK_RELOC32, HUNK_SYMBOL, HUNK_DEBUG, HUNK_END, HUNK_HEADER = 0x3EC, 0x3F0, 0x3F1, 0x3F2, 0x3F3
HUNK_RELOC32SHORT, HUNK_DREL32 = 0x3FC, 0x3F7


def relocs(path):
    d = open(path, 'rb').read()
    p = 0

    def long():
        nonlocal p
        v = struct.unpack('>I', d[p:p + 4])[0]
        p += 4
        return v

    def word():
        nonlocal p
        v = struct.unpack('>H', d[p:p + 2])[0]
        p += 2
        return v

    assert long() == HUNK_HEADER
    while long():
        pass
    long()
    first, last = long(), long()
    nh = last - first + 1
    for _ in range(nh):
        long()
    out = []
    h = 0
    while p < len(d) and h < nh:
        t = long() & 0x3FFFFFFF
        if t in (HUNK_CODE, HUNK_DATA):
            n = long() & 0x3FFFFFFF
            p += n * 4
        elif t == HUNK_BSS:
            long()
        elif t == HUNK_RELOC32:
            while True:
                n = long()
                if not n:
                    break
                target = long()
                for _ in range(n):
                    out.append((h, long(), target))
        elif t in (HUNK_RELOC32SHORT, HUNK_DREL32):
            while True:
                n = word()
                if not n:
                    break
                target = word()
                for _ in range(n):
                    out.append((h, word(), target))
            if p & 2:
                p += 2
        elif t in (HUNK_SYMBOL,):
            while True:
                n = long()
                if not n:
                    break
                p += n * 4
                long()
        elif t in (HUNK_DEBUG, HUNK_NAME, HUNK_UNIT):
            n = long()
            p += n * 4
        elif t == HUNK_END:
            h += 1
        else:
            raise SystemExit('ramrel: unknown hunk type %x' % t)
    return nh, out


def main():
    exe, win, outname, labels = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4:]
    nh, rel = relocs(exe)
    if nh != len(labels):
        raise SystemExit('ramrel: %d hunks, %d labels given' % (nh, len(labels)))
    places = sorted((h, off) for h, off, t in rel if t == win)
    lines = [';\tGenerated by amiga/tools/ramrel.py: the longs that hold RAM window addresses.',
             'ram_relocs']
    for h, off in places:
        lines.append('\tdc.l\t%s+$%X' % (labels[h], off))
    lines.append('\tdc.l\t0')
    open(outname, 'w').write('\n'.join(lines) + '\n')
    print('ramrel: %d places' % len(places))


if __name__ == '__main__':
    main()
