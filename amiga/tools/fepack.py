#!/usr/bin/env python3
"""The screens shown only now and then, kept deflated (build step of the Amiga port)."""
import os, sys, zlib

GROUPS = [
    ('the EA Sports screen', [('EASportsMap', 'EASportsMap.bin')]),
    ('the title screen', [('TitleScreenImg', 'Title94-1.map.jim'), ('NHLShieldImg', 'Title94-2.map.jim'),
                          ('PAlogoImg', 'Title94-3.map.jim'), ('TitleImg', 'Title94-4.map.jim')]),
    ('the game setup screen', [('GameSetUpMap', 'GameSetUp94-1.map.jim'), ('GameSetUpMap2', 'GameSetUp94-2.map.jim'),
                               ('SetupMenuMap', 'GameSetupBkgd1.map.jim'), ('SetupFramerMap', 'GameSetupBkgd2.map.jim')]),
]


def deflate(b):
    c = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
    return c.compress(b) + c.flush()


def main():
    gdir, outname = sys.argv[1:3]
    blocks, equs, sizes = [], [], []
    at = 0
    for name, files in GROUPS:
        data = bytearray()
        for label, fn in files:
            equs.append('%s\tequ\tFEWIN+%d\t\t;(%s)' % (label, at + len(data), name))
            data += open(os.path.join(gdir, fn), 'rb').read()
            data += b'\0' * (len(data) & 1)
        z = deflate(bytes(data))
        assert zlib.decompress(z, -15) == bytes(data)
        blocks.append((name, z, len(data), at))
        sizes.append(len(data))
        at += len(data)
    win = (at + 15) & ~15
    lines = [';\tGenerated by amiga/tools/fepack.py: the pictures of the EA Sports, title and game setup',
             ';\tscreens, deflated (fe_open inflates a screen\'s into its place in the window FEWIN).', '',
             'FEWSIZE\tequ\t%d\t\t\t;the window: the three screens\', whole 16 bytes' % win,
             'FESCREENS\tequ\t%d' % len(blocks)]
    lines += equs
    lines += ['', '\tsection\tgame,code', ';\tper screen: its block, its place in the window', 'fe_table']
    for i, (name, z, n, at) in enumerate(blocks):
        lines.append('\tdc.l\tfe_block%d,%d\t\t;%s' % (i, at, name))
    for i, (name, z, n, at) in enumerate(blocks):
        lines.append('fe_block%d\t\t\t\t;%s: %d bytes, %d deflated' % (i, name, n, len(z)))
        zz = z + b'\0\0'
        for k in range(0, len(zz), 32):
            lines.append('\tdc.b\t' + ','.join('$%02X' % v for v in zz[k:k + 32]))
        lines.append('\teven')
    open(outname, 'w').write('\n'.join(lines) + '\n')
    print('fepack: %d screens, %d bytes, %d deflated, window %d' %
          (len(blocks), sum(sizes), sum(len(b[1]) for b in blocks), win))


if __name__ == '__main__':
    main()
