#!/usr/bin/env python3
"""The screens shown only now and then, kept deflated (build step of the Amiga port).

The EA Sports screen, the title screen and the game setup screen take their pictures from data
the game reads only while it sets the screen up (and the setup screen when it moves its menu
frame). Those files are not in the program as they are: each screen's are deflated into one
block here, and their labels are addresses in a window that fe_open (render.asm) inflates the
screen's block into when the screen begins. The window is the top of the sprite image cache,
given back when a game starts (fe_close). graphics94.asm loses the files (patches.py).

Usage: fepack.py <Extracted/NHL94/Graphics directory> out.i
"""
import os, sys, zlib

GROUPS = [                      # (screen, [(label, file)])
    ('the EA Sports screen', [('EASportsMap', 'EASportsMap.bin')]),
    ('the title screen', [('TitleScreenImg', 'Title94-1.map.jim'), ('NHLShieldImg', 'Title94-2.map.jim'),
                          ('PAlogoImg', 'Title94-3.map.jim'), ('TitleImg', 'Title94-4.map.jim')]),
    ('the game setup screen', [('GameSetUpMap', 'GameSetUp94-1.map.jim'), ('GameSetUpMap2', 'GameSetUp94-2.map.jim'),
                               ('SetupMenuMap', 'GameSetupBkgd1.map.jim'), ('SetupFramerMap', 'GameSetupBkgd2.map.jim')]),
]


def deflate(b):
    c = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
    return c.compress(b) + c.flush()


def main():
    gdir, outname = sys.argv[1:3]
    blocks, equs, sizes = [], [], []
    for name, files in GROUPS:
        data = bytearray()
        for label, fn in files:
            equs.append('%s\tequ\tFEWIN+%d\t\t;(%s)' % (label, len(data), name))
            data += open(os.path.join(gdir, fn), 'rb').read()
            data += b'\0' * (len(data) & 1)
        z = deflate(bytes(data))
        assert zlib.decompress(z, -15) == bytes(data)
        blocks.append((name, z, len(data)))
        sizes.append(len(data))
    win = (max(sizes) + 15) & ~15
    lines = [';\tGenerated by amiga/tools/fepack.py: the pictures of the EA Sports, title and game setup',
             ';\tscreens, deflated (fe_open inflates a screen\'s into the window FEWIN).', '',
             'FEWSIZE\tequ\t%d\t\t\t;the window: the largest screen\'s, whole 16 bytes' % win,
             'FESCREENS\tequ\t%d' % len(blocks)]
    lines += equs
    lines += ['', '\tsection\tgame,code', ';\tper screen: its block, its bytes inflated', 'fe_table']
    for i, (name, z, n) in enumerate(blocks):
        lines.append('\tdc.l\tfe_block%d,%d\t\t;%s' % (i, n, name))
    for i, (name, z, n) in enumerate(blocks):
        lines.append('fe_block%d\t\t\t\t;%s: %d bytes, %d deflated' % (i, name, n, len(z)))
        zz = z + b'\0\0'                    # (the inflater may read 2 bytes past the end)
        for k in range(0, len(zz), 32):
            lines.append('\tdc.b\t' + ','.join('$%02X' % v for v in zz[k:k + 32]))
        lines.append('\teven')
    open(outname, 'w').write('\n'.join(lines) + '\n')
    print('fepack: %d screens, %d bytes, %d deflated, window %d' %
          (len(blocks), sum(sizes), sum(len(z) for _, z, _ in blocks), win))


if __name__ == '__main__':
    main()
