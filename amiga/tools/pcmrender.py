#!/usr/bin/env python3
"""The game's PCM sounds as Amiga samples (build step of the Amiga port): signed 8 bit, at most
MAXHZ samples a second (as fast as Paula plays: a period of 124).

The Z80 driver plays a PCM sound from its start (pcm_sample_table) up to the first 0 byte, at a
rate set per note. They are kept as they are (6.5 to 12 kHz), but the one played faster than
Paula can (the glass at 29 kHz), which is resampled down a little, and the voice plays it at a
period longer by the same factor (sound.asm), so it keeps its pitch.

Needs numpy. Usage: pcmrender.py <src/sound94.asm> <Extracted/NHL94/Sound directory> out.i
"""
import glob, math, os, re, sys
import numpy as np

MAXHZ = 28600                       # Paula's clock / 124
PCMHZ = 30594                       # the Z80 PCM loop: a rate step is 1/256 sample at this
FNUM = [0x146, 0x159, 0x16E, 0x184, 0x19B, 0x1B3, 0x1CD, 0x1E8, 0x205, 0x224, 0x245, 0x268]


def rom_layout(asm):
    """The bytes from sfx_shotbh_pcm to fm_instrument_patches as assembled, and the labels."""
    src = open(asm).read()
    a, b = src.index('\nsfx_shotbh_pcm'), src.index('\nfm_instrument_patches')
    base = os.path.dirname(os.path.abspath(asm))
    blob, labels = bytearray(), {}
    for line in src[a:b].splitlines():
        t = line.split(';')[0].strip()
        if not t:
            continue
        m = re.match(r'^(sfx_\w+)$', t)
        if m:
            labels[m.group(1)] = len(blob)
            continue
        m = re.match(r'incbin\s+(\S+)', t)
        if m:
            blob += open(os.path.join(base, m.group(1).replace('\\', '/')), 'rb').read()
        elif t == 'even':
            blob += b'\0' * (len(blob) & 1)
        elif re.match(r'dc\.b\s+\$FF$', t):
            blob.append(0xFF)
        else:
            raise SystemExit('pcmrender.py: %s?' % t)
    table = re.findall(r'^\s+dc\.l\s+(\w+),0\s+;patch \$(6[0-9A-F])', src[src.index('\npcm_sample_table'):a], re.M)
    return bytes(blob), labels, [None if l == '0' else l for l, _ in table]


def max_rates(sound_dir):
    """The fastest rate (Hz) each PCM patch is played at in the songs and sound effects."""
    rates = {}
    for fn in sorted(glob.glob(os.path.join(sound_dir, '*cmdstream*.bin'))):
        d = open(fn, 'rb').read()
        patch = {}
        for i in range(0, len(d) - 3, 4):
            st = d[i + 1]
            if st == 0:
                continue
            if st & 0x70 == 0x40:
                patch[st & 15] = d[i + 2]
            if st & 0x70 == 0x10 and d[i + 3] and patch.get(st & 15, 0) >= 0x60:
                n = d[i + 2]
                if n // 12 <= 8:
                    r = PCMHZ * (FNUM[n % 12] >> (8 - n // 12)) / 256
                    p = patch[st & 15] - 0x60
                    rates[p] = max(rates.get(p, 0), r)
    return rates


def resample(x, f):
    """x at 1/f the rate (f > 1): windowed sinc low-pass at 0.45 of the new rate."""
    half = 16
    n = int(len(x) / f)
    out = np.zeros(n)
    for j in range(n):
        c = j * f
        k = np.arange(int(c) - half * math.ceil(f), int(c) + half * math.ceil(f) + 1)
        k = k[(k >= 0) & (k < len(x))]
        t = (c - k) / f
        w = 0.42 + 0.5 * np.cos(np.pi * t / (half + 1)) + 0.08 * np.cos(2 * np.pi * t / (half + 1))
        h = 0.9 * np.sinc(0.9 * t) * np.where(np.abs(t) <= half + 1, w, 0)
        out[j] = np.dot(x[k], h) / f
    return out


def main():
    asm, sound_dir, outname = sys.argv[1:4]
    blob, labels, table = rom_layout(asm)
    rates = max_rates(sound_dir)
    signed = (np.frombuffer(blob, np.uint8).astype(np.int16) - 128)
    lines = [';\tGenerated by amiga/tools/pcmrender.py: the PCM sounds, signed 8 bit, at most %d Hz.' % MAXHZ,
             '', '\tsection\tsndchip,data_c', 'pcm_rom']
    data = (signed.astype(np.int8).view(np.uint8)).tobytes()

    def emit(bs):
        if len(bs) & 1:
            bs += b'\0'
        for i in range(0, len(bs), 32):
            lines.append('\tdc.b\t' + ','.join('$%02X' % v for v in bs[i:i + 32]))
        return len(bs)

    emit(data)                                  # the sounds kept as they are, all in one
    entries = []
    slow = {}                                   # start label -> (its own label, bytes, factor)
    for p, label in enumerate(table):
        if label is None:
            entries.append(None)
            continue
        start = labels[label]
        n = blob.index(0, start) - start        # up to the 0 that ends it
        users = [q for q, l in enumerate(table) if l == label]
        top = max(rates.get(q, 0) for q in users)
        if top <= MAXHZ:
            entries.append(('pcm_rom+%d' % start, n & ~1, 256))   # (whole words: not the 0)
            continue
        if label not in slow:
            f = top / MAXHZ
            y = resample(signed[start:start + n].astype(float), f)
            bs = (np.clip(np.round(y), -127, 127).astype(np.int8).view(np.uint8)).tobytes()
            own = 'pcm_' + label
            lines.append(own)
            slow[label] = (own, emit(bs), int(round(f * 256)))
            print('pcmrender: %s %d bytes at up to %d Hz -> %d bytes, period x %.3f'
                  % (label, n, top, slow[label][1], f))
        own, size, k = slow[label]
        entries.append((own, size, k))
    lines += ['', '\tsection\tgame,code', '',
              ';\tper PCM patch ($60 up): sample (0: none), length (words), period factor (8.8)',
              'snd_pcm_tab']
    for e in entries:
        lines.append('\tdc.l\t0\n\tdc.w\t0,0' if e is None else
                     '\tdc.l\t%s\n\tdc.w\t%d,%d' % (e[0], e[1] // 2, e[2]))
    open(outname, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
