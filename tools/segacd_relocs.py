#!/usr/bin/env python3
"""Match cartridge instructions to HOCKEY.BIN and list address pairs.

A window of six adjacent instructions matches when the mnemonics and the
operand shape match (addresses replaced). A pair is kept when that window
occurs once in the cartridge and the same cartridge address always becomes
the same disc address.

  python3 tools/segacd_relocs.py lst/nhl94.bin cdbin/HOCKEY.BIN
"""

import re
import sys
from collections import defaultdict

from capstone import Cs, CS_ARCH_M68K, CS_MODE_BIG_ENDIAN, CS_MODE_M68K_000

md = Cs(CS_ARCH_M68K, CS_MODE_M68K_000 | CS_MODE_BIG_ENDIAN)
WINDOW = 6


def insns(blob, start, end, base):
    out = []
    pc = start
    while pc + 2 <= end:
        got = None
        for insn in md.disasm(blob[pc:pc + 12], base + pc):
            got = insn
            break
        if got is None or got.address != base + pc or got.size < 2:
            pc += 2
            continue
        # Zeros decode as ori #0. That is data, not an instruction stream.
        if got.bytes == b"\x00" * got.size:
            pc += 2
            continue
        out.append(got)
        pc += got.size
    runs = []
    run = []
    prev = None
    for insn in out:
        if prev is not None and insn.address == prev:
            run.append(insn)
        else:
            if len(run) >= WINDOW:
                runs.append(run)
            run = [insn]
        prev = insn.address + insn.size
    if len(run) >= WINDOW:
        runs.append(run)
    return runs


def shape(insn):
    op = re.sub(r"\$[0-9a-f]+", "@", insn.op_str)
    return insn.mnemonic + " " + op


BRANCH = {
    "bra", "bsr", "jmp", "jsr", "dbra", "dbf", "dbt",
    "beq", "bne", "bhi", "bls", "bcc", "bcs", "bpl", "bmi",
    "bvc", "bvs", "bge", "bgt", "ble", "blt",
}
BRANCH |= {f"db{c}" for c in ("eq", "ne", "hi", "ls", "cc", "cs", "pl", "mi", "vc", "vs", "ge", "gt", "le", "lt")}


def addrs(insn):
    # Branch targets move because abs.w instructions became abs.l. Only absolute
    # operands (.w / .l), not (pc) or a branch displacement, are a real relocation.
    op = insn.op_str
    if "(pc)" in op:
        return []
    base = insn.mnemonic.split(".")[0]
    if base in BRANCH and ".l" not in op:
        return []
    found = []
    for match in re.finditer(r"\$([0-9a-f]+)(\.[wl])?", op):
        if match.group(2):
            found.append(int(match.group(1), 16))
    return found


def main():
    rom = open(sys.argv[1], "rb").read()
    cd = open(sys.argv[2], "rb").read()
    rom_runs = insns(rom, 0x200, 0x4B5C0, 0) + insns(rom, 0xF66EE, len(rom), 0)
    cd_runs = insns(cd, 0, len(cd), 0)

    index = defaultdict(list)
    for run in rom_runs:
        for i in range(len(run) - WINDOW + 1):
            key = tuple(shape(insn) for insn in run[i:i + WINDOW])
            index[key].append(run[i:i + WINDOW])

    votes = defaultdict(int)
    for run in cd_runs:
        for i in range(len(run) - WINDOW + 1):
            win = run[i:i + WINDOW]
            key = tuple(shape(insn) for insn in win)
            hits = index.get(key)
            if not hits or len(hits) != 1:
                continue
            src = hits[0]
            for a, b in zip(src, win):
                aa, bb = addrs(a), addrs(b)
                if len(aa) != len(bb):
                    continue
                for x, y in zip(aa, bb):
                    if x != y and x > 0xFF and y > 0xFF:
                        votes[(x, y)] += 1

    by_src = defaultdict(lambda: defaultdict(int))
    for (x, y), n in votes.items():
        by_src[x][y] += n

    def plausible(src, dst):
        src_ok = src < 0x100000 or src >= 0xFFFF8000
        dst_ok = dst < 0x400000 or dst >= 0xFFFF8000
        return src_ok and dst_ok

    rows = []
    for src, dests in by_src.items():
        best, n = max(dests.items(), key=lambda kv: kv[1])
        others = sum(dests.values()) - n
        if n < 2 or others or not plausible(src, best):
            continue
        rows.append((src, best, n))
    rows.sort()
    print("# Generated by tools/segacd_relocs.py. Absolute operands only; a pair is kept")
    print("# when one cartridge address always maps to one disc address, twice or more.")
    print(f"{'cartridge':<12} {'sega cd':<12} times")
    for src, dst, n in rows:
        print(f"${src:08X}   ${dst:08X}   {n}")
    print(f"{len(rows)} pairs")


if __name__ == "__main__":
    main()
